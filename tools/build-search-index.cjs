/* Offline search index for the library: every lesson, example and exercise set, with its page and step key.
   Reads the built chapters v2/<id>.js (BOOK.src) and writes search-index.js in the repo root (precached by sw.js).
   usage:  node tools/build-search-index.cjs [--check]
   --check: exit 1 if search-index.js is missing or out of date (used by release.test.cjs).
   The step keys MUST follow v2/engine.js parse(): <lesson>-<section index>-<step index>, opened by #l=<lesson>&k=<key>. */
const fs=require('fs'), path=require('path'), vm=require('vm');
const root=path.join(__dirname,'..'), CHECK=process.argv.includes('--check');
const idx=fs.readFileSync(path.join(root,'index.html'),'utf8');
/* chapters in library order, with grade and chapter title, straight from index.html BOOKS */
const books=[]; let grade='';
for(const m of idx.matchAll(/\{id:'(\w+)',t:'([^']+)'|\{n:(\d+),t:'([^']+)'[^}]*?v2:'(\w+)'/g)){
  if(m[1]) grade=m[2].split('·').pop().trim(); else books.push({id:m[5],n:+m[3],t:m[4],grade}); }
const plain=s=>String(s||'').replace(/\$\$?([^$]*)\$\$?/g,(m,t)=>t.replace(/\\[a-zA-Z]+|\\[,;:! ]/g,' ').replace(/[{}^_]/g,'').replace(/\s+/g,' ')).replace(/\*\*|\[\[\w+:|\]\]/g,'').replace(/\s+/g,' ').trim();
const toLatinDigits=s=>s.replace(/[٠-٩]/g,d=>'٠١٢٣٤٥٦٧٨٩'.indexOf(d));
function pages(s){ const m=toLatinDigits(s).match(/ص\s*(\d+)(?:\s*[–-]\s*(\d+))?/); return m?[+m[1],+(m[2]||m[1])]:null; }

function lessons(src){        /* structure only — mirrors v2/engine.js parse() */
  const L=[]; let les=null, sec=null, st=null;
  for(const raw of src.split('\n')){ const s=raw.trim(); if(!s||s.startsWith('//')) continue;
    if(s.startsWith('===')){ const [id,no,t,pg,d]=s.slice(3).split('|').map(x=>x.trim()); les={id,no,t,pg,d:d||'',secs:[]}; L.push(les); sec=null; st=null; continue; }
    if(s.startsWith('---')){ sec={steps:[]}; les.secs.push(sec); st=null; continue; }
    if(s.startsWith('>>>')){ st={lines:[],cls:s}; if(!sec){ sec={steps:[]}; les.secs.push(sec); } sec.steps.push(st); continue; }
    if(st) st.lines.push(s); }
  return L; }

const out=[];   /* [chapter, lesson, key|'', kind, label, title, p1, p2, words] ; kind: L lesson · E example · X exercises */
for(const b of books){
  const f=path.join(root,'v2',b.id+'.js'); if(!fs.existsSync(f)) continue;
  const ctx={window:{},document:{},console:{log(){},warn(){}},Math,navigator:{}}; ctx.self=ctx.window; ctx.globalThis=ctx;
  vm.runInNewContext(fs.readFileSync(f,'utf8'),ctx,{filename:f}); const src=(ctx.window.BOOK||ctx.BOOK).src;
  for(const l of lessons(src)){
    const lp=pages('ص '+l.pg)||[0,0];
    out.push([b.id,l.id,'','L',l.no,plain(l.t),lp[0],lp[1],plain(l.d)]);
    const seen=new Set();
    l.secs.forEach((sec,si)=>sec.steps.forEach((st,ki)=>{
      const k=st.lines.find(x=>/^(k|h2):/.test(x)); if(!k) return;
      const lab=plain(k.replace(/^(k|h2):\s*/,'')); const ex=/^مثال\s*\d/.test(lab), xs=/تمارين|تمرين/.test(lab);
      if(!ex&&!xs) return; if(/ليس من الكتاب/.test(lab)) return;
      const id=lab.replace(/\s+/g,' '); if(seen.has(id)) return; seen.add(id);
      const h2=st.lines.find(x=>/^h2:/.test(x)), q=st.lines.find(x=>/^p:/.test(x));
      const p=pages(lab)||lp;
      out.push([b.id,l.id,`${l.id}-${si}-${ki}`,ex?'E':'X',lab,plain(h2?h2.slice(3):l.t),p[0],p[1],plain(q?q.slice(2):'').slice(0,160)]); })); } }

const meta=Object.fromEntries(books.map(b=>[b.id,[b.grade,b.n,b.t]]));
const js=`/* generated by tools/build-search-index.cjs — do not edit */\nself.MB_SEARCH={v:1,books:${JSON.stringify(meta)},rows:${JSON.stringify(out).replace(/\],\[/g,'],\n[')}};\n`;
const dst=path.join(root,'search-index.js'), same=fs.existsSync(dst)&&fs.readFileSync(dst,'utf8')===js;
if(CHECK){ if(!same){ console.log('FAIL search-index.js out of date (run node tools/build-search-index.cjs)'); process.exit(1); } console.log(`PASS search index in sync (${out.length} entries)`); }
else { if(!same) fs.writeFileSync(dst,js); console.log(`wrote search-index.js: ${out.length} entries (${out.filter(r=>r[3]==='E').length} examples, ${out.filter(r=>r[3]==='X').length} exercise sets), ${(js.length/1024).toFixed(1)} KB`); }
